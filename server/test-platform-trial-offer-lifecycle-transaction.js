require("dotenv").config();

const assert = require("node:assert/strict");
const mongoose = require("mongoose");

const SubscriptionPlan = require("./models/SubscriptionPlan");
const SubscriptionPlanVersion = require("./models/SubscriptionPlanVersion");
const PlatformTrialOffer = require("./models/PlatformTrialOffer");
const PlatformTrialOfferAudit = require("./models/PlatformTrialOfferAudit");

const {
  createDraftPlanVersion,
  publishPlanVersion,
} = require("./services/subscriptionPlanVersionService");

const {
  createDraftTrialOffer,
  updateDraftTrialOffer,
  publishTrialOffer,
  setTrialOfferEnabled,
  retireTrialOffer,
} = require("./services/platformTrialOfferService");

const TEST_DATABASE = "coaching_management_test";

const CORE_FEATURES = [
  "AUTHENTICATION",
  "ROLE_AUTHORIZATION",
  "TENANT_ISOLATION",
  "PERMISSION_AUTHORIZATION",
  "ACCOUNT_SECURITY",
  "SESSION_SECURITY",
  "INSTITUTE_PROFILE",
  "BASIC_DASHBOARD",
  "SECURITY_AUDIT",
];

const FEATURES = [
  ...CORE_FEATURES.map((key) => ({ key, enabled: true })),
  { key: "STUDENT_MANAGEMENT", enabled: true },
  { key: "TEACHER_MANAGEMENT", enabled: true },
];

const LIMITS = [
  { key: "MAX_STUDENTS", value: 100 },
  { key: "MAX_TEACHERS", value: 10 },
];

function createTestIds() {
  return {
    actorId: new mongoose.Types.ObjectId(),
    planId: null,
    planVersionId: null,
    offerId: null,
  };
}

async function createPublishedTestPlan(ids) {
  const suffix = `${Date.now()}_${new mongoose.Types.ObjectId()
    .toString()
    .slice(-6)}`;

  const plan = new SubscriptionPlan({
    code: `TEST_TRIAL_${suffix}`,
    name: `Trial Lifecycle Test ${suffix}`,
    description: "Temporary lifecycle integration test plan",
    isActive: true,
    createdBy: ids.actorId,
    updatedBy: ids.actorId,
  });

  await plan.save();
  ids.planId = plan._id;

  const draft = await createDraftPlanVersion({
    planId: plan._id,
    actorId: ids.actorId,
    configuration: {
      amount: 0,
      currency: "INR",
      durationDays: 30,
      paymentRequired: false,
      features: FEATURES,
      limits: LIMITS,
    },
  });

  ids.planVersionId = draft._id;

  await publishPlanVersion({
    planId: plan._id,
    versionId: draft._id,
    actorId: ids.actorId,
  });

  const savedPlan = await SubscriptionPlan.findById(plan._id);

  assert.equal(
    String(savedPlan.currentPublishedVersion),
    String(draft._id)
  );

  return {
    planId: plan._id,
    planVersionId: draft._id,
  };
}

async function cleanupTestRecords(ids) {
  // Direct collection cleanup is deliberately restricted to IDs
  // generated by this test. Never use collection-wide deletion.
  if (ids.offerId) {
    await PlatformTrialOfferAudit.collection.deleteMany({
      offerId: ids.offerId,
    });

    await PlatformTrialOffer.collection.deleteOne({
      _id: ids.offerId,
    });
  }

  if (ids.actorId) {
    await PlatformTrialOfferAudit.collection.deleteMany({
      actorId: ids.actorId,
    });
  }

  if (ids.planId) {
    await SubscriptionPlanVersion.collection.deleteMany({
      planId: ids.planId,
    });

    await SubscriptionPlan.collection.deleteOne({
      _id: ids.planId,
    });
  }
}

async function testLifecycleAndAudit() {
  const ids = createTestIds();
  const originalAuditSave = PlatformTrialOfferAudit.prototype.save;

  try {
    const { planId, planVersionId } =
      await createPublishedTestPlan(ids);

    // 1. Create a disabled DRAFT offer.
    const createdOffer = await createDraftTrialOffer({
      planId,
      planVersionId,
      durationDays: 14,
      eligibility: "NEW_INSTITUTES_ONLY",
      actorId: ids.actorId,
    });

    ids.offerId = createdOffer._id;

    let savedOffer = await PlatformTrialOffer.findById(ids.offerId);

    assert.ok(savedOffer);
    assert.equal(savedOffer.status, "DRAFT");
    assert.equal(savedOffer.enabled, false);

    console.log("PASS: Real database DRAFT creation");

    // 2. Update the DRAFT configuration.
    const updatedOffer = await updateDraftTrialOffer({
      offerId: ids.offerId,
      actorId: ids.actorId,
      configuration: {
        durationDays: 21,
      },
    });

    assert.equal(updatedOffer.durationDays, 21);

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);

    assert.equal(savedOffer.durationDays, 21);
    assert.equal(savedOffer.status, "DRAFT");

    console.log("PASS: DRAFT update and audit");

    // 3. Inject an audit failure during publication.
    // The publication and its audit must roll back together.
    PlatformTrialOfferAudit.prototype.save = async function (...args) {
      if (
        this.isNew &&
        this.eventType === "TRIAL_OFFER_PUBLISHED"
      ) {
        throw new Error("INJECTED_PUBLISH_AUDIT_FAILURE");
      }

      return originalAuditSave.apply(this, args);
    };

    let publicationFailed = false;

    try {
      await publishTrialOffer({
        offerId: ids.offerId,
        actorId: ids.actorId,
      });
    } catch (error) {
      publicationFailed = true;

      assert.match(
        error.message,
        /INJECTED_PUBLISH_AUDIT_FAILURE/
      );
    } finally {
      PlatformTrialOfferAudit.prototype.save = originalAuditSave;
    }

    assert.equal(publicationFailed, true);

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);

    assert.equal(
      savedOffer.status,
      "DRAFT",
      "Failed publication must leave the offer in DRAFT"
    );

    assert.equal(savedOffer.enabled, false);

    let publishedAuditCount =
      await PlatformTrialOfferAudit.countDocuments({
        offerId: ids.offerId,
        eventType: "TRIAL_OFFER_PUBLISHED",
      });

    assert.equal(
      publishedAuditCount,
      0,
      "Failed publication must not leave a publication audit"
    );

    console.log(
      "PASS: Publication audit failure rolls back status change"
    );

    // 4. Publish successfully.
    await publishTrialOffer({
      offerId: ids.offerId,
      actorId: ids.actorId,
    });

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);

    assert.equal(savedOffer.status, "PUBLISHED");
    assert.equal(savedOffer.enabled, false);
    assert.ok(savedOffer.publishedAt);
    assert.equal(String(savedOffer.publishedBy), String(ids.actorId));

    console.log("PASS: Publication and audit persist");

    // 5. Enable the offer.
    await setTrialOfferEnabled({
      offerId: ids.offerId,
      enabled: true,
      actorId: ids.actorId,
    });

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);
    assert.equal(savedOffer.enabled, true);

    console.log("PASS: Enable event and audit persist");

    // 6. Disable the offer.
    await setTrialOfferEnabled({
      offerId: ids.offerId,
      enabled: false,
      actorId: ids.actorId,
    });

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);
    assert.equal(savedOffer.enabled, false);

    console.log("PASS: Disable event and audit persist");

    // 7. Enable it again, then retire it while enabled.
    await setTrialOfferEnabled({
      offerId: ids.offerId,
      enabled: true,
      actorId: ids.actorId,
    });

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);
    assert.equal(savedOffer.enabled, true);

    await retireTrialOffer({
      offerId: ids.offerId,
      actorId: ids.actorId,
    });

    savedOffer = await PlatformTrialOffer.findById(ids.offerId);

    assert.equal(savedOffer.status, "RETIRED");
    assert.equal(savedOffer.enabled, false);
    assert.ok(savedOffer.retiredAt);
    assert.equal(String(savedOffer.retiredBy), String(ids.actorId));

    console.log(
      "PASS: Retirement disables enabled offer before retiring it"
    );

    // 8. Verify persisted audit history.
    const auditRecords = await PlatformTrialOfferAudit.find({
      offerId: ids.offerId,
    }).sort({ occurredAt: 1, _id: 1 }).lean();

    const eventTypes = auditRecords.map((record) => record.eventType);

    const expectedEvents = [
      "TRIAL_OFFER_CREATED",
      "TRIAL_OFFER_UPDATED",
      "TRIAL_OFFER_PUBLISHED",
      "TRIAL_OFFER_ENABLED",
      "TRIAL_OFFER_DISABLED",
      "TRIAL_OFFER_ENABLED",
      "TRIAL_OFFER_DISABLED",
      "TRIAL_OFFER_RETIRED",
    ];

    assert.deepEqual(eventTypes, expectedEvents);

    assert.ok(
      auditRecords.every(
        (record) =>
          String(record.actorId) === String(ids.actorId) &&
          String(record.offerId) === String(ids.offerId)
      ),
      "All audit records must identify the correct actor and offer"
    );

    assert.equal(
      auditRecords[auditRecords.length - 1].snapshot.status,
      "RETIRED"
    );

    console.log(
      "PASS: All lifecycle audit events persist in expected order"
    );
  } finally {
    PlatformTrialOfferAudit.prototype.save = originalAuditSave;
    await cleanupTestRecords(ids);
  }
}

async function main() {
  assert.ok(
    process.env.MONGO_URI,
    "MONGO_URI is missing from the server .env file"
  );

  await mongoose.connect(process.env.MONGO_URI, {
    dbName: TEST_DATABASE,
  });

  if (mongoose.connection.name !== TEST_DATABASE) {
    throw new Error(
      `Unsafe database "${mongoose.connection.name}". ` +
      `Expected "${TEST_DATABASE}". Aborting.`
    );
  }

  console.log(`Connected to isolated database: ${TEST_DATABASE}`);

  try {
    await Promise.all([
      SubscriptionPlan.init(),
      SubscriptionPlanVersion.init(),
      PlatformTrialOffer.init(),
      PlatformTrialOfferAudit.init(),
    ]);

    await testLifecycleAndAudit();

    console.log(
      "\nAll platform trial offer lifecycle transaction tests passed."
    );
  } finally {
    await mongoose.disconnect();
  }
}

main().catch(async (error) => {
  console.error("\nFAIL:", error);
  await mongoose.disconnect().catch(() => {});
  process.exitCode = 1;
});